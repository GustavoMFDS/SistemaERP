#requires -Version 5.1
<#
  Initial signed release staging, BEFORE SQL bootstrap or ERP registration.
  Breaks the dependency cycle: SQL migrations need approved Program Files
  tools, but ERP SCM registration needs a DATABASE_URL_FILE generated by SQL.
  Default is read-only. No database/service or fiscal operation here.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)][string]$SourceBundleDir,
    [string]$StageDir=(Join-Path $env:ProgramFiles 'EsteriumApprovedSetup'),
    [string]$ApprovedManifestSHA256='',
    [string]$TrustedPublisherThumbprint='',
    [switch]$Apply
)
$ErrorActionPreference='Stop'
Set-StrictMode -Version Latest
if ($env:OS -ne 'Windows_NT') { throw 'First-install release staging requires Windows.' }
if ($Apply) {
    if ($ApprovedManifestSHA256 -cnotmatch '^[A-Fa-f0-9]{64}$' -or
        $TrustedPublisherThumbprint -cnotmatch '^[A-Fa-f0-9]{40}$') {
        throw 'Release staging needs independently approved digest and publisher.'
    }
    # Verify the helpers BEFORE executing code from their PowerShell files.
    foreach ($helper in @('verify-esterium-bundle.ps1','check-esterium-signed-release.ps1')) {
        $helperPath=Join-Path $PSScriptRoot $helper
        $signed=Get-AuthenticodeSignature -LiteralPath $helperPath
        if ($signed.Status -ne [Management.Automation.SignatureStatus]::Valid -or
            $null -eq $signed.SignerCertificate -or
            $signed.SignerCertificate.Thumbprint.ToUpperInvariant() -cne
              $TrustedPublisherThumbprint.ToUpperInvariant()) {
            throw 'Release staging verifier is not signed by approved publisher.'
        }
    }
    $sig=Get-AuthenticodeSignature -LiteralPath $PSCommandPath
    if ($sig.Status -ne [Management.Automation.SignatureStatus]::Valid -or
        $null -eq $sig.SignerCertificate -or
        $sig.SignerCertificate.Thumbprint.ToUpperInvariant() -cne
          $TrustedPublisherThumbprint.ToUpperInvariant()) {
        throw 'Release staging helper is not signed by approved publisher.'
    }
}
function Assert-Path([string]$path,[bool]$directory) {
    if (-not [IO.Path]::IsPathRooted($path) -or $path.StartsWith('\\')) {
        throw 'Release staging requires local disk paths.'
    }
    $full=[IO.Path]::GetFullPath($path).TrimEnd('\')
    $cursor=$full
    while ($cursor) {
        $item=Get-Item -LiteralPath $cursor -Force -ErrorAction Stop
        if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
            throw 'Release staging forbids linked paths.'
        }
        $parent=Split-Path -Parent $cursor
        if ($parent -eq $cursor) { break }
        $cursor=$parent
    }
    if ((Get-Item -LiteralPath $full).PSIsContainer -ne $directory) {
        throw 'Wrong release staging path type.'
    }
    return $full
}
$source=Assert-Path $SourceBundleDir $true
$dest=[IO.Path]::GetFullPath($StageDir).TrimEnd('\')
$program=[IO.Path]::GetFullPath($env:ProgramFiles).TrimEnd('\')+'\'
if (-not [IO.Path]::IsPathRooted($StageDir) -or $StageDir.StartsWith('\\') -or
    -not $dest.StartsWith($program,[StringComparison]::OrdinalIgnoreCase) -or
    $dest.StartsWith($source+'\',[StringComparison]::OrdinalIgnoreCase) -or
    $source.StartsWith($dest+'\',[StringComparison]::OrdinalIgnoreCase) -or
    (Test-Path -LiteralPath $dest)) {
    throw 'Release staging requires a NEW dedicated Program Files directory.'
}
$parent=Split-Path -Parent $dest
$cursor=$parent
while ($cursor) {
    if (Test-Path -LiteralPath $cursor) {
        $item=Get-Item -LiteralPath $cursor -Force -ErrorAction Stop
        if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
            throw 'Release staging destination cannot have linked ancestors.'
        }
    }
    $next=Split-Path -Parent $cursor
    if ($next -eq $cursor) { break }
    $cursor=$next
}
& (Join-Path $PSScriptRoot 'verify-esterium-bundle.ps1') -BundleDir $source | Out-Null
if (-not $Apply) {
    Write-Output 'PLAN: verify bundle integrity and copy only approved Windows release contents to protected Program Files.'
    Write-Output 'PLAN: stage signing-verified SQL tools before database setup and service registration, without starting anything.'
    return
}
if (-not [Security.Principal.WindowsPrincipal]::new([Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole(
    [Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw 'Release staging requires elevated administrator.'
}
$gate=@{ExpectedManifestSHA256=$ApprovedManifestSHA256;ExpectedPublisherThumbprint=$TrustedPublisherThumbprint}
& (Join-Path $PSScriptRoot 'check-esterium-signed-release.ps1') -BundleDir $source @gate | Out-Null
$partial=Join-Path $parent ('.esterium-approved-'+[Guid]::NewGuid().ToString('N'))
$committed=$false
try {
    [IO.Directory]::CreateDirectory($partial) | Out-Null
    & icacls.exe $partial '/inheritance:r' '/grant:r' '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'Cannot protect staged release folder ACL.' }
    Copy-Item -LiteralPath (Join-Path $source 'esterium-server.exe') -Destination $partial -ErrorAction Stop
    foreach ($name in @('tools','web','migrations')) {
        Copy-Item -LiteralPath (Join-Path $source $name) -Destination (Join-Path $partial $name) -Recurse -ErrorAction Stop
    }
    foreach ($name in @('bundle-manifest.json','README_LOCAL.md')) {
        Copy-Item -LiteralPath (Join-Path $source $name) -Destination $partial -ErrorAction Stop
    }
    # Verify copied bytes and publisher BEFORE and AFTER atomic rename.
    & (Join-Path $PSScriptRoot 'check-esterium-signed-release.ps1') -BundleDir $partial @gate | Out-Null
    if (Test-Path -LiteralPath $dest) { throw 'Concurrent release staging created the destination.' }
    Move-Item -LiteralPath $partial -Destination $dest -ErrorAction Stop
    $committed=$true
    & (Join-Path $PSScriptRoot 'check-esterium-signed-release.ps1') -BundleDir $dest @gate | Out-Null
    Write-Output 'PASS: approved Windows release staged under Program Files with SYSTEM/Administrators-only write ACL.'
    Write-Output 'NEXT: run SQL bootstrap from staged tools, then register ERP using staged source and generated DATABASE_URL_FILE.'
    Write-Output 'NOT READY: no PostgreSQL/Garnet/ERP service has been started or enabled.'
} finally {
    if (-not $committed -and (Test-Path -LiteralPath $partial)) {
        Remove-Item -LiteralPath $partial -Recurse -Force -ErrorAction SilentlyContinue
    }
}
