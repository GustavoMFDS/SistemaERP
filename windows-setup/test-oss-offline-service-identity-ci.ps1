#requires -Version 5.1
<#
Proves that pg-service.secret generated by the native unsigned MIT EXE
can authenticate a non-admin local Windows account. Disposable hosted CI only.
Does NOT create a permanent customer account or Windows service.
#>
[CmdletBinding()]
param([Parameter(Mandatory=$true)][string]$IntegratedExe)
$ErrorActionPreference='Stop'
Set-StrictMode -Version Latest
if($env:OS -ne 'Windows_NT' -or $env:GITHUB_ACTIONS -ne 'true' -or
   $env:RUNNER_ENVIRONMENT -ne 'github-hosted' -or
   $env:ESTERIUM_PG_ZIP_DISPOSABLE_CI -ne '1' -or
   $env:ESTERIUM_OPEN_SOURCE_PLAN_DISPOSABLE_CI -ne '1' -or
   $env:ESTERIUM_NATIVE_DATA_DISPOSABLE_CI -ne '1') {
    throw 'Offline service identity test requires disposable hosted Windows CI.'
}
$principal=[Security.Principal.WindowsPrincipal]::new([Security.Principal.WindowsIdentity]::GetCurrent())
if(-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw 'Offline identity CI test requires Administrator.'
}
if([string]::IsNullOrWhiteSpace($env:RUNNER_TEMP)) { throw 'Runner temp missing.' }
$runner=[IO.Path]::GetFullPath($env:RUNNER_TEMP).TrimEnd('\')+'\'
$exe=[IO.Path]::GetFullPath($IntegratedExe)
if(-not $exe.StartsWith($runner,[StringComparison]::OrdinalIgnoreCase) -or
   (Split-Path -Leaf $exe) -cne 'EsteriumERP-Setup-TECHNICAL-PREVIEW.exe' -or
   -not(Test-Path -LiteralPath $exe -PathType Leaf) -or
   ((Get-Item -LiteralPath $exe -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)) {
    throw 'Test needs the integrated preview EXE from runner temp.'
}
$root=Join-Path $env:ProgramData 'Esterium'
$dir=Join-Path $root 'Secrets'
$file=Join-Path $dir 'pg-service.secret'
$marker=Join-Path $root 'oss-data-layout.json'
foreach($path in @($root,$dir,$file,$marker)){
    if(-not(Test-Path -LiteralPath $path) -or
       ((Get-Item -LiteralPath $path -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)){
        throw 'Offline protected stage missing or linked.'
    }
}
$journal=Get-Content -LiteralPath $marker -Raw | ConvertFrom-Json -ErrorAction Stop
if($journal.schemaVersion -ne 1 -or $journal.phase -cne 'OFFLINE_SECRETS_ONLY' -or
   $journal.secretsGenerated -ne $true -or $journal.databaseInitialized -ne $false -or
   $journal.servicesInstalled -ne $false -or $journal.backupsConfigured -ne $false){
    throw 'Expected offline-credentials-only journal.'
}
if(-not (Get-Acl -LiteralPath $root).AreAccessRulesProtected){
    throw 'Native ProgramData stage root must have non-inherited ACL.'
}
foreach($path in @($root,$dir,$file)){
    $acl=Get-Acl -LiteralPath $path
    $bad=@($acl.GetAccessRules($true,$true,[Security.Principal.SecurityIdentifier]) |
        Where-Object {
            $_.AccessControlType -eq 'Allow' -and
            $_.IdentityReference.Value -notin @('S-1-5-18','S-1-5-32-544')
        })
    if($bad.Count){throw 'An unapproved SID can read offline identity material.'}
}
if(@(Get-Service -Name @('EsteriumPostgreSQL16','EsteriumGarnet','EsteriumERP') -ErrorAction SilentlyContinue).Count){
    throw 'Production service name exists, refusing CI identity test.'
}
$journalHash=(Get-FileHash -LiteralPath $marker -Algorithm SHA256).Hash
# Detect a changed or swapped file after the restricted-identity read probe.
$secretNames=@('pg-super.secret','pg-service.secret','pg-app.secret',
    'garnet-password.secret','jwt.secret','metrics.secret')
$secretHashes=@{}
foreach($secretName in $secretNames){
    $secretFile=Join-Path $dir $secretName
    if(-not(Test-Path -LiteralPath $secretFile -PathType Leaf) -or
       ((Get-Item -LiteralPath $secretFile -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)){
        throw 'Offline identity CI needs six intact, nonlinked secret files.'
    }
    $secretHashes[$secretName]=(Get-FileHash -LiteralPath $secretFile -Algorithm SHA256).Hash
}
$name='eos'+[Guid]::NewGuid().ToString('N').Substring(0,12)
$work=Join-Path $env:RUNNER_TEMP ('esterium-identity-'+[Guid]::NewGuid().ToString('N'))
$out=Join-Path $work 'whoami.out'
$err=Join-Path $work 'whoami.err'
$created=$false
$secret=$null
$secure=$null
$proc=$null
$lsaHelper=Join-Path $PSScriptRoot 'test-postgres-oss-lsa-ci.ps1'
$lsaTouched=$false
$serviceName='EsteriumCIOfflinePG'+[Guid]::NewGuid().ToString('N').Substring(0,12)
try {
    $secret=[IO.File]::ReadAllText($file).TrimEnd([char]13,[char]10)
    if($secret -cnotmatch '^Q9_z[A-Za-z0-9_-]{64}$'){
        throw 'Offline service password format mismatch.'
    }
    $secure=ConvertTo-SecureString $secret -AsPlainText -Force
    $secret=$null
    if($null -ne (Get-LocalUser -Name $name -ErrorAction SilentlyContinue)){
        throw 'Unique disposable account already exists.'
    }
    $user=New-LocalUser -Name $name -Password $secure -Description 'Disposable offline password proof' -ErrorAction Stop
    $created=$true
    if($null -eq $user -or $null -eq $user.SID){throw 'Account SID unavailable.'}
    $sid=[string]$user.SID.Value
    $adminGroup=Get-LocalGroup -SID 'S-1-5-32-544'
    if(@(Get-LocalGroupMember -Group $adminGroup.Name | Where-Object { $_.SID.Value -ceq $sid }).Count){
        throw 'Disposable identity unexpectedly acquired local admin role.'
    }
    [IO.Directory]::CreateDirectory($work) | Out-Null
    & icacls.exe $work '/inheritance:r' '/grant:r' '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' ('*'+$sid+':(OI)(CI)M') | Out-Null
    if($LASTEXITCODE -ne 0){throw 'Could not protect test output folder.'}
    $credential=[PSCredential]::new(($env:COMPUTERNAME+'\'+$name),$secure)
    # Verify pre-state, grant exactly SeServiceLogonRight, inspect LSA.
    # No service is registered; no customer identity is changed.
    & $lsaHelper -Action VerifyRevoked -Sid $sid -OfflineSecretAccount
    $lsaTouched=$true # cleanup even when the grant/verification throws
    & $lsaHelper -Action Grant -Sid $sid -OfflineSecretAccount
    & $lsaHelper -Action VerifyGranted -Sid $sid -OfflineSecretAccount
    # SCM registration proof: only a unique CI-owned service, always
    # DISABLED and STOPPED. No cluster exists at this location and the
    # service must NEVER be started in this test.
    $verifiedPgCtl=Join-Path $env:ProgramFiles 'EsteriumOpenSourcePostgresBin\pgsql\bin\pg_ctl.exe'
    if(-not(Test-Path -LiteralPath $verifiedPgCtl -PathType Leaf) -or
       ((Get-Item -LiteralPath $verifiedPgCtl -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)){
        throw 'Only native ZIP-stage PostgreSQL pg_ctl.exe may appear in the CI service image.'
    }
    if($null -ne (Get-Service -Name $serviceName -ErrorAction SilentlyContinue)){
        throw 'Unique disposable service name unexpectedly already exists.'
    }
    $unusedCluster=Join-Path $root 'PostgresData\cluster'
    if(Test-Path -LiteralPath $unusedCluster){
        throw 'Offline CI SCM test must not adopt an existing PostgreSQL cluster.'
    }
    $serviceCommand='"'+$verifiedPgCtl+'" runservice -N "'+$serviceName+'" -D "'+$unusedCluster+'" -w'
    New-Service -Name $serviceName -BinaryPathName $serviceCommand -Credential $credential -StartupType Disabled -DisplayName ('Disposable offline PostgreSQL identity '+$serviceName) -ErrorAction Stop | Out-Null
    $registered=@(Get-CimInstance -ClassName Win32_Service -Filter ("Name='"+$serviceName+"'") -ErrorAction Stop)
    $expectedLocal='.\'+$name
    if($registered.Count -ne 1 -or $registered[0].StartMode -cne 'Disabled' -or
       $registered[0].State -cne 'Stopped' -or [int]$registered[0].ProcessId -ne 0 -or
       $registered[0].StartName -notin @($credential.UserName,$expectedLocal) -or
       $registered[0].PathName -cne $serviceCommand){
        throw 'SCM stored incorrect disabled-state, image or non-admin offline service identity.'
    }
    Write-Output 'PASS: CI-only PostgreSQL service registered DISABLED and STOPPED using offline non-admin identity; never started.'
    $parameters=@{
        FilePath=(Join-Path $env:WINDIR 'System32\whoami.exe')
        ArgumentList=@('/user','/fo','csv','/nh')
        Credential=$credential
        Wait=$true
        PassThru=$true
        RedirectStandardOutput=$out
        RedirectStandardError=$err
        ErrorAction='Stop'
    }
    # Password is held in PSCredential, never supplied as argv/log text.
    $proc=Start-Process @parameters
    if($null -eq $proc -or $proc.ExitCode -ne 0){throw 'Offline secret failed Windows local logon.'}
    $tokenOutput=[IO.File]::ReadAllText($out)
    if(-not $tokenOutput.Contains($sid)){
        throw 'Logged-on account SID does not match new non-admin user.'
    }
    $secretChanged=$false
    foreach($secretName in $secretNames){
        if((Get-FileHash -LiteralPath (Join-Path $dir $secretName) -Algorithm SHA256).Hash -cne $secretHashes[$secretName]){
            $secretChanged=$true
        }
    }
    if((Get-FileHash -LiteralPath $marker -Algorithm SHA256).Hash -cne $journalHash -or $secretChanged){
        throw 'Identity logon modified protected offline state.'
    }
    # The service account must authenticate successfully yet MUST NOT read
    # the original installer-only credential file. All subprocess arguments
    # contain a fixed path/script, never secret material.
    $denyScript=@'
$root=Join-Path $env:ProgramData 'Esterium'
$targets=@(
    'Secrets\pg-super.secret',
    'Secrets\pg-service.secret',
    'Secrets\pg-app.secret',
    'Secrets\garnet-password.secret',
    'Secrets\jwt.secret',
    'Secrets\metrics.secret',
    'oss-data-layout.json'
)
foreach($relative in $targets){
    $source=Join-Path $root $relative
    try {
        $handle=[IO.File]::Open($source,[IO.FileMode]::Open,[IO.FileAccess]::Read,[IO.FileShare]::Read)
        $handle.Dispose()
        exit 71  # SECURITY FAILURE: non-admin could read a protected file
    } catch [UnauthorizedAccessException] {
        continue
    } catch {
        exit 72  # Unexpected failure must not be mistaken for ACL denial
    }
}
exit 0
'@
    # Use a short, fixed script path rather than a long encoded command.
    # CreateProcessWithLogonW (used by -Credential) can reject the latter.
    # The test script contains only a static file path, never a secret.
    $probeScript=Join-Path $work 'deny-secret-read.ps1'
    [IO.File]::WriteAllText($probeScript,$denyScript,[Text.UTF8Encoding]::new($false))
    $deniedParams=@{
        FilePath=(Join-Path $env:WINDIR 'System32\WindowsPowerShell\v1.0\powershell.exe')
        ArgumentList=@('-NoProfile','-NonInteractive','-ExecutionPolicy','Bypass','-File',('"'+$probeScript+'"'))
        Credential=$credential
        Wait=$true
        PassThru=$true
        RedirectStandardOutput=(Join-Path $work 'denied.out')
        RedirectStandardError=(Join-Path $work 'denied.err')
        ErrorAction='Stop'
    }
    $denied=Start-Process @deniedParams
    if($null -eq $denied -or $denied.ExitCode -ne 0){
        throw 'Ephemeral non-admin account could access offline secret or ACL probe failed.'
    }
    $denied.Dispose()
    Write-Output 'PASS: authenticated non-admin Windows account cannot read any of six protected secrets or the install journal.'
    Write-Output 'PASS: protected pg-service secret authenticated a real disposable non-admin Windows logon.'
    Write-Output 'PASS: Windows token SID matches the local account; no passwords in command arguments.'
    Write-Output 'PASS: offline identity SCM registration remained disabled; no Windows service process was started.'
}
finally {
    $secret=$null
    $secure=$null
    if($null -ne $proc){$proc.Dispose()}
    # Teardown order is mandatory: SCM service, LSA right, Windows user.
    # Nested finally clauses attempt all three even if an earlier step fails.
    try {
        $existing=Get-Service -Name $serviceName -ErrorAction SilentlyContinue
        if($null -ne $existing){
            if($existing.Status -ne [ServiceProcess.ServiceControllerStatus]::Stopped){
                throw 'Disposable offline service unexpectedly started; refuse unsafe cleanup.'
            }
            & (Join-Path $env:WINDIR 'System32\sc.exe') delete $serviceName | Out-Null
            if($LASTEXITCODE -ne 0){throw 'Cannot deregister disposable offline Windows service.'}
            for($i=0;$i -lt 40;$i++){
                if($null -eq (Get-Service -Name $serviceName -ErrorAction SilentlyContinue)){break}
                Start-Sleep -Milliseconds 250
            }
            if($null -ne (Get-Service -Name $serviceName -ErrorAction SilentlyContinue)){
                throw 'Disposable offline Windows service survived SCM cleanup.'
            }
            Write-Output 'PASS: disposable offline PostgreSQL SCM registration removed without starting.'
        }
    } finally {
        try {
            if($lsaTouched){
                & $lsaHelper -Action Revoke -Sid $sid -OfflineSecretAccount
                & $lsaHelper -Action VerifyRevoked -Sid $sid -OfflineSecretAccount
                Write-Output 'PASS: offline CI service-logon right revoked and verified absent.'
            }
        } finally {
            if($created){
                Remove-LocalUser -Name $name -ErrorAction Stop
                if($null -ne (Get-LocalUser -Name $name -ErrorAction SilentlyContinue)){
                    throw 'Temporary Windows account remains after cleanup.'
                }
            }
        }
    }
    if(Test-Path -LiteralPath $work){Remove-Item -LiteralPath $work -Recurse -Force -ErrorAction Stop}
    $secretChanged=$false
    foreach($secretName in $secretNames){
        if((Get-FileHash -LiteralPath (Join-Path $dir $secretName) -Algorithm SHA256).Hash -cne $secretHashes[$secretName]){
            $secretChanged=$true
        }
    }
    if((Get-FileHash -LiteralPath $marker -Algorithm SHA256).Hash -cne $journalHash -or $secretChanged){
        throw 'Offline secrets or journal changed during test cleanup.'
    }
    Write-Output 'PASS: ephemeral offline credential account removed; protected secrets preserved.'
}
