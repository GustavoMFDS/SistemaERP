package db

import (
	"context"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
)

// DBTX is the minimal interface shared by *pgxpool.Pool, pgx.Tx, and pgx.Conn.
// It allows infrastructure repositories to accept either a transaction or a pool.
//
// Etapa 4 (Unit of Work) will formalize transaction boundaries.
type DBTX interface {
	Exec(ctx context.Context, sql string, arguments ...any) (pgconn.CommandTag, error)
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}
